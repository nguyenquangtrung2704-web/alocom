create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  order_date date not null,
  dish_name text not null,
  unit_price numeric(12,0) not null check (unit_price >= 0),
  quantity integer not null default 1 check (quantity between 1 and 20),
  note text,
  created_at timestamptz not null default now()
);

create index if not exists orders_order_date_idx
on public.orders(order_date);

alter table public.orders enable row level security;

drop policy if exists "anon_can_read_orders" on public.orders;
create policy "anon_can_read_orders"
on public.orders
for select
to anon
using (true);

drop policy if exists "anon_can_insert_orders" on public.orders;
create policy "anon_can_insert_orders"
on public.orders
for insert
to anon
with check (true);

drop policy if exists "anon_can_delete_orders" on public.orders;
create policy "anon_can_delete_orders"
on public.orders
for delete
to anon
using (true);

grant select, insert, delete on table public.orders to anon;
grant usage, select on sequence public.orders_id_seq to anon;


