-- Tạo bucket public để ảnh có thể hiển thị trên app
insert into storage.buckets (id, name, public)
values ('menu-images', 'menu-images', true)
on conflict (id) do update set public = true;

-- Cho phép đọc ảnh công khai
drop policy if exists "Public read menu images" on storage.objects;
create policy "Public read menu images"
on storage.objects
for select
to public
using (bucket_id = 'menu-images');

-- Cho phép ứng dụng upload ảnh bằng publishable/anon key
drop policy if exists "Anon upload menu images" on storage.objects;
create policy "Anon upload menu images"
on storage.objects
for insert
to anon
with check (bucket_id = 'menu-images');

-- Cho phép ghi đè/cập nhật ảnh nếu cần
drop policy if exists "Anon update menu images" on storage.objects;
create policy "Anon update menu images"
on storage.objects
for update
to anon
using (bucket_id = 'menu-images')
with check (bucket_id = 'menu-images');

-- Cho phép xóa file trong bucket nếu sau này cần
drop policy if exists "Anon delete menu images" on storage.objects;
create policy "Anon delete menu images"
on storage.objects
for delete
to anon
using (bucket_id = 'menu-images');




